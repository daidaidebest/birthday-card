"""Finds the lights painted into the cozy study (fairy-light bulbs, the fire, lamps) and the window glass, and writes
site/js/scenes/study-lights.js so the book and cake scenes can make them twinkle and flicker, and fly lanterns
past the glass. Run after replacing site/assets/img/study-land.webp / study-port.webp."""
import json, os
import numpy as np, cv2
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
out = {}
for name in ('study-land', 'study-port'):
    a = np.asarray(Image.open(f'{ROOT}/site/assets/img/{name}.webp').convert('RGB')).astype(np.int32)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    lum = (r * 3 + g * 6 + b) / 10
    warm = (lum > 200) & (r > 225) & (r - b > 70)
    n, lab, st, cen = cv2.connectedComponentsWithStats(warm.astype(np.uint8), connectivity=8)
    bulbs, fires = [], []
    for i in range(1, n):
        x, y, w, h, area = st[i]
        if area < 3: continue
        c = [round(float(cen[i][0])), round(float(cen[i][1]))]
        if area <= 160 and max(w, h) <= 22: bulbs.append(c + [int(max(w, h))])
        elif area > 160: fires.append([int(x), int(y), int(w), int(h)])
    # the window glass: night-blue (or moonlit) pixels in the largest blue region
    blue = ((b - r > 25) & (b > 55)) | ((lum > 170) & (b >= r - 10) & (b > 150))
    blue = cv2.morphologyEx(blue.astype(np.uint8), cv2.MORPH_CLOSE, np.ones((5, 5), np.uint8))
    joined = cv2.dilate(blue, np.ones((41, 41), np.uint8))   # bridge the window bars between the panes
    n, lab, st, _ = cv2.connectedComponentsWithStats(joined, connectivity=8)
    k = 1 + int(np.argmax(st[1:, cv2.CC_STAT_AREA]))
    x, y, w, h, _ = st[k]
    out[name] = {'bulbs': bulbs, 'fires': fires, 'glass': [int(x), int(y), int(x + w), int(y + h)]}
    m = ((lab == k) & (blue > 0)).astype(np.uint8) * 255
    m = cv2.GaussianBlur(m, (0, 0), .8)
    Image.fromarray(m[y:y + h, x:x + w], 'L').save(f'{ROOT}/site/assets/img/{name}-glass.png', optimize=True)
    print(name, len(bulbs), 'bulbs', len(fires), 'lights', 'glass', out[name]['glass'])
with open(f'{ROOT}/site/js/scenes/study-lights.js', 'w') as f:
    f.write('// Generated by tools/study_lights.py: lights painted into the cozy study, in painting pixels.\n'
            '//   bulbs [x, y, size] · fires [x, y, w, h] (fire and lamps) · glass [x0, y0, x1, y1] of the window, whose mask is img/<name>-glass.png\n')
    f.write('export const LIGHTS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
